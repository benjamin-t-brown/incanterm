/** Saved dialogue with a stable ID, including a request that has been turned off. */
export interface VoiceLine {
  lineId: string;
  requested: boolean;
  speaker: string;
  text: string;
  revision: string;
}

export function isVoiceLineId(value: unknown): value is string {
  return typeof value === 'string' && /^[A-Za-z0-9_-]{1,128}$/.test(value);
}

export function isVoiceRevision(value: unknown): value is string {
  return typeof value === 'string' && /^v1-[0-9a-f]{16}$/.test(value);
}

/** Only the parsed, spoken content contributes to the revision (never the source location). */
export function getVoiceRevision(speaker: string, text: string): string {
  // Version 1: FNV-1a 64 over the UTF-8 JSON tuple. This is a change detector, not a
  // file checksum. Tuple encoding keeps quotes, separators, and empty fields unambiguous.
  let hash = 0xcbf29ce484222325n;
  for (const byte of new TextEncoder().encode(JSON.stringify([speaker, text]))) {
    hash = BigInt.asUintN(64, (hash ^ BigInt(byte)) * 0x100000001b3n);
  }
  return `v1-${hash.toString(16).padStart(16, '0')}`;
}

export interface VoiceEditSettings {
  gainDb: number;
  cleanup: { profileId: string; strengthDb: number; algorithmVersion: string } | null;
}

const originalEdits: VoiceEditSettings = { gainDb: 0, cleanup: null };

/** Omitted take settings mean original audio at unity gain. JSON key order is immaterial. */
export function areVoiceEditsEqual(
  first: VoiceEditSettings | undefined,
  second: VoiceEditSettings | undefined,
): boolean {
  const a = first ?? originalEdits;
  const b = second ?? originalEdits;
  if (a.gainDb !== b.gainDb) return false;
  if (!a.cleanup || !b.cleanup) return a.cleanup === b.cleanup;
  return (
    a.cleanup.profileId === b.cleanup.profileId &&
    a.cleanup.strengthDb === b.cleanup.strengthDb &&
    a.cleanup.algorithmVersion === b.cleanup.algorithmVersion
  );
}

export interface VoiceRecordingSnapshot {
  readonly lineId: string;
  readonly recordedRevision: string;
  readonly speaker: string;
  readonly text: string;
}

/** Capture at Record, before microphone, upload, or retry callbacks can see a newer script. */
export function getVoiceRecordingSnapshot(line: VoiceLine): VoiceRecordingSnapshot {
  if (!line.requested) throw new Error('Voice has not been requested for this line.');
  if (line.revision !== getVoiceRevision(line.speaker, line.text)) {
    throw new Error('Recording revision does not match the speaker and text.');
  }
  return {
    lineId: line.lineId,
    recordedRevision: line.revision,
    speaker: line.speaker,
    text: line.text,
  };
}

export interface VoiceTake extends VoiceRecordingSnapshot {
  readonly takeId: string;
  readonly mimeType: string;
  /** ISO 8601 timestamp generated by the editor server. */
  readonly createdAt: string;
  favorite?: boolean;
  edits?: VoiceEditSettings;
}

export interface VoiceApproval {
  lineId: string;
  revision: string;
  takeId: string;
  edits: VoiceEditSettings;
  confirmedOlderTake?: true;
}

export type VoiceStatus =
  | 'needs-recording'
  | 'needs-review'
  | 'needs-pickup'
  | 'approved'
  | 'no-voice-requested'
  | 'archived';

function hasValidVoiceSnapshots(line: VoiceLine, take: VoiceTake): boolean {
  return (
    line.revision === getVoiceRevision(line.speaker, line.text) &&
    take.recordedRevision === getVoiceRevision(take.speaker, take.text)
  );
}

export function createVoiceApproval(
  line: VoiceLine,
  take: VoiceTake,
  edits: VoiceEditSettings,
  options: { confirmOlderTake?: boolean } = {},
): VoiceApproval {
  if (!line.requested || take.lineId !== line.lineId) {
    throw new Error('Approval requires a requested line and a take belonging to that line.');
  }
  if (!hasValidVoiceSnapshots(line, take)) {
    throw new Error('Line or take revision does not match its speaker and text.');
  }
  const older = take.recordedRevision !== line.revision;
  if (older && !options.confirmOlderTake) {
    throw new Error('Confirm reuse of the take recorded for earlier wording.');
  }
  return {
    lineId: line.lineId,
    revision: line.revision,
    takeId: take.takeId,
    edits: { ...edits, cleanup: edits.cleanup && { ...edits.cleanup } },
    ...(older && { confirmedOlderTake: true }),
  };
}

function getApprovedVoiceTake(
  line: VoiceLine,
  takes: readonly VoiceTake[],
  approvals: readonly VoiceApproval[],
): VoiceTake | undefined {
  if (!line.requested) return;
  const matches = approvals.filter((a) => a.lineId === line.lineId && a.revision === line.revision);
  if (matches.length !== 1) return;
  const [approval] = matches;
  const candidates = takes.filter((t) => t.lineId === line.lineId && t.takeId === approval.takeId);
  if (candidates.length !== 1) return;
  const [take] = candidates;
  if (
    approval.edits &&
    areVoiceEditsEqual(approval.edits, take.edits) &&
    (take.recordedRevision === line.revision || approval.confirmedOlderTake === true) &&
    hasValidVoiceSnapshots(line, take)
  ) {
    return take;
  }
}

/** Check the candidate for publication against all saved approvals, not a preselected one. */
export function isVoiceApprovalValid(
  line: VoiceLine,
  take: VoiceTake,
  approvals: readonly VoiceApproval[],
): boolean {
  return getApprovedVoiceTake(line, [take], approvals) !== undefined;
}

/**
 * Pass null only for a confirmed absence in saved scripts. Catalog errors and duplicate
 * IDs are reported by the catalog, not classified as archived or actionable lines.
 */
export function getVoiceStatus(
  line: VoiceLine | null,
  takes: readonly VoiceTake[],
  approvals: readonly VoiceApproval[],
): VoiceStatus {
  if (!line) return 'archived';
  if (!line.requested) return 'no-voice-requested';
  const history = takes.filter((take) => take.lineId === line.lineId);
  if (history.length === 0) return 'needs-recording';
  if (getApprovedVoiceTake(line, history, approvals)) return 'approved';
  return history.some((take) => take.recordedRevision === line.revision)
    ? 'needs-review'
    : 'needs-pickup';
}
